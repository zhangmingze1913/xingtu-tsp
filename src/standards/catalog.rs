//! Machine-readable standards catalog.
//!
//! This is a status registry, not a conformance claim. It gives tests and the
//! `/api/integrations/standards` endpoint one source of truth for what the
//! current build actually implements.

use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Implementation {
    Done,
    Partial,
    Missing,
    NotApplicable,
}

