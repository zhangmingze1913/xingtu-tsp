pub fn counts() -> (usize, usize, usize, usize) {
    let mut done = 0;
    let mut partial = 0;
    let mut missing = 0;
    let mut na = 0;
    for spec in CATALOG {
        match spec.implementation {
            Done => done += 1,
            Partial => partial += 1,
            Missing => missing += 1,
            NotApplicable => na += 1,
        }
    }
    (done, partial, missing, na)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_has_unique_message_keys_and_counts() {
        let mut keys = std::collections::HashSet::new();
        for spec in CATALOG {
            assert!(keys.insert((spec.standard, spec.message_id)));
        }
        let (done, partial, missing, na) = counts();
        assert_eq!(done + partial + missing + na, CATALOG.len());
        assert!(done > 0 && partial > 0);
        assert_eq!(missing, 0);
    }
}
